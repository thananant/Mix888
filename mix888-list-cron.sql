select jobid,
       jobname                                        as "ชื่องาน",
       schedule                                       as "เวลา (UTC)",
       active                                         as "เปิดอยู่",
       regexp_replace(command, '\s+', ' ', 'g')       as "คำสั่ง (ดูชื่อ functions/v1/xxx)"
  from cron.job
 order by jobname;
