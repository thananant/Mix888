--  รันทั้งไฟล์ใน Supabase (โปรเจกต์ Mix Fresh) → SQL Editor → Run (รันซ้ำได้)
--
--  ทำไมต้องรัน: ปุ่ม "🗑 ลบทิ้ง" ในหน้าเช็คสลิปตกค้าง ลบไฟล์จากถัง slips
--  แต่ถังยังไม่เปิดสิทธิ์ลบให้ผู้ใช้ที่ล็อกอิน — Supabase จะตอบเหมือนสำเร็จ
--  ทั้งที่ไฟล์ยังอยู่ (รีเฟรชแล้วเด้งกลับมา) ไฟล์นี้เปิดสิทธิ์ลบเฉพาะถัง slips
--  ให้เฉพาะคนที่ล็อกอินระบบเท่านั้น
-- ============================================================

drop policy if exists "slips_delete_auth" on storage.objects;
create policy "slips_delete_auth" on storage.objects
  for delete to authenticated
  using (bucket_id = 'slips');
